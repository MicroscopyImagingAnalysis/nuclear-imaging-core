def gen_mask_fast(binary_image,cenx,ceny,nbins,maxdist):

    masks = np.zeros((nbins,) + binary_image.shape, np.int64)
    dr = maxdist / nbins
    bins_dr = np.array([(i+0.5) for i in range(nbins)])
    binary = np.ones_like(binary_image)
    binary[int(ceny),int(cenx)] = 0


    if binary.ndim == 2:
        distance = ndi.distance_transform_edt(binary)
    else:
        distance = ndi.distance_transform_edt(binary, sampling=(1, 1, 1))

    for i in range(nbins):
        dist_min = i * dr
        dist_max = (i + 1) * dr
        masks[i] = (distance >= dist_min) & (distance < dist_max)

    print("radial masks", masks.shape, np.unique(masks))
    return masks, bins_dr
