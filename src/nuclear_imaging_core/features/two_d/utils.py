
import numpy as np
from scipy import ndimage as ndi
from skimage import feature, segmentation, morphology, measure

def get_peaks(raw:np.ndarray,mask1:np.ndarray,mask2:np.ndarray,
              alpha: float=1.5,min_dist:float=4,min_size:int=27):

    filtered = raw[(mask1 > 0)]


    print("min_size, mean int, std int",min_size,filtered.min(),filtered.mean(),filtered.std(),filtered.max())
    try:
        threshold = filtered.mean() + alpha * filtered.std()

    except:
        print(raw[mask1>0].shape,raw[mask2>0].shape,raw[(mask1 > 0) & (mask2 > 0)].shape)
        threshold = 0


    foci_mask = np.zeros_like(raw,dtype=bool)
    foci_mask[(raw > threshold) & (mask1>0) & (mask2 > 0)] = True
    print("foci mask pre-filt",foci_mask[foci_mask==True].shape)

    # Identify local intensity maxima
    coords = feature.peak_local_max(raw, min_distance=min_dist,labels=foci_mask)
    peak_mask = np.zeros(raw.shape, dtype=bool)
    peak_mask[tuple(coords.T)] = True
    markers, _ = ndi.label(peak_mask)


    # Watershed segment the images using the local maxima
    labels = segmentation.watershed(-raw, markers, mask=foci_mask)
    labels = morphology.remove_small_objects(labels, min_size=min_size)
    labels = measure.label(labels).astype(np.int32, copy=False)
    final_coords = feature.peak_local_max(raw, min_distance=1,labels=labels,num_peaks_per_label=1)

    print(alpha,markers.shape,len(np.unique(labels[labels>0])),final_coords.shape)

    return labels,final_coords








def gen_mask_erosion(binary_image,ib,nbins,maxdistxy,maxdistz=None):

    """
    Generate masks by progressively eroding from the spheroid.
    Parameters:
    binary_image (numpy.ndarray): A 2D binary image where the spheroid is represented by non-zero values.
    nbins (int): Number of bins or masks to generate.
    maxdistxy (float): Maximum distance in the xy-plane for erosion.
    maxdistz (float): Maximum distance in the z-plane for erosion.
    Returns:
    tuple: A tuple containing:
        - masks (numpy.ndarray): An array of shape (nbins, binary_image.shape[0], binary_image.shape[1])
            containing the masks generated by erosion.
        - bins_dr (numpy.ndarray): An array of bin distances used for erosion.
    """

    #### get masks by progressively eroding from the spheroid
    # masks = np.zeros((nbins,) + binary_image.shape, np.int64)
    mask = np.zeros(binary_image.shape, np.int64)
    drxy = maxdistxy/nbins
    boundary_shell_xy = int(drxy)
    # drz = maxdistz/nbins
    # boundary_shell_z = max(1,int(0.25*drxy)) #int(drz)


    bins_dr = np.array([(i+0.5) for i in range(nbins)])

    #### need to do checking if bulk still exists, else masks is empty
    bw = binary_image > 0


    for i in range(ib+1):
        bulk = np.array([],np.int64)

        if bw.ndim == 3:
            bulk = np.copy(bw)
            for z in range(bw.shape[0]):
                bulk[z] = morphology.binary_erosion(bw[z],
                            morphology.square(boundary_shell_xy))
        if bw.ndim == 2:
            bulk = morphology.binary_erosion(bw,
                            morphology.square(boundary_shell_xy))


        if bulk[bulk > 0].size > 0:
            shell = np.subtract(bw * 1, bulk * 1) ## true in bw and subtract the eroded part
            bw = np.copy(bulk)
            if i == ib:
                mask = np.copy(shell)
            # masks[i] = np.copy(shell)

        else:
            ## nothing left
            if i == ib:
                mask = np.zeros_like(binary_image,np.int64)
            # masks[i] = np.zeros_like(binary_image,np.int64)
            ## dont update bw and dont calculate shell

    # print("erosion masks",masks.shape,np.unique(masks))
    return mask,bins_dr


